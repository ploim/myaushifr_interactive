export type Mood = 'idle' | 'happy' | 'analyze' | 'alarm'

/** Результат шага. Определяет цвет бейджа и поведение трека. */
export type SceneStatus = 'info' | 'pass' | 'warn' | 'unknown' | 'block' | 'deliver'

export interface Speaker {
  name: string
  /** Короткая пиксельная плашка: кто говорит. */
  badge: string
  /** Иконка спикера — как правило, совпадает с иконкой узла сцены. */
  icon: PixelMap
  /** Стиль «вне защиты» — для атакующего и нейтральных персонажей. */
  tone: 'szi' | 'outside'
  /** Экран иконки красный (атакующий). */
  evil?: boolean
}

export interface Scene {
  id: string
  title: string
  stage: string
  status: SceneStatus
  statusLabel: string
  speaker: Speaker
  /** Концептуальная функция средства защиты (для карточки). */
  sziRole?: string
  /** Объяснение от лица спикера. */
  narration: string
  mood: Mood
  /** Реплика маскота. */
  quote: string
  /** Финальная сцена: вместо панели — итоговая карточка. */
  finale?: boolean
  /** Маркер на треке едет дальше «под замком». */
  markerLocked?: boolean
}

export interface Act {
  id: string
  title: string
  /** Реплика маскота на весь акт (показывается на первой сцене акта). */
  quote: string
  scenes: Scene[]
}

export interface Scenario {
  id: string
  title: string
  tagline: string
  /** Плашка уровня угрозы на карточке выбора. */
  threat: string
  /** high — красная карточка, mid — янтарная. */
  threatLevel: 'high' | 'mid'
  /** Тон вердикта: danger — красная итоговая карточка, success — зелёная. */
  verdictTone: 'danger' | 'success'
  /** Чем закончится — подпись на карточке выбора. */
  outcomeText: string
  /** Состояние последнего узла трека в финале. */
  finalNodeState: NodeState
  /** Свой конвейер узлов для каждого сюжета. */
  stages: readonly Stage[]
  /** Маркер трека (12×8): письмо / вредонос / данные. */
  marker: PixelMap
  /** Итоговая карточка. */
  verdictTitle: string
  verdictSubtitle: string
  summary: readonly { status: SceneStatus; text: string }[]
  acts: Act[]
}

const stageIcon = (stages: readonly Stage[], id: string): PixelMap =>
  stages.find((s) => s.id === id)!.icon

