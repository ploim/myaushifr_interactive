export const SCENARIOS: readonly Scenario[] = [malicious, legit]

// ----------------------------------------------------------------------------
// Плоский список шагов прогона
// ----------------------------------------------------------------------------
export interface Step {
  scenario: Scenario
  act: Act
  actIndex: number
  actFirstScene: boolean
  scene: Scene
  index: number
  total: number
}

export function flatten(scenario: Scenario): Step[] {
  const steps: Step[] = []
  for (const [actIndex, act] of scenario.acts.entries()) {
    act.scenes.forEach((scene, sceneIndex) => {
      steps.push({
        scenario,
        act,
        actIndex,
        actFirstScene: sceneIndex === 0,
        scene,
        index: steps.length,
        total: 0,
      })
    })
  }
  return steps.map((s) => ({ ...s, total: steps.length }))
}

/** Реплика акта или сцены по id — для редактора и хранилища. */
export interface QuoteItem {
  kind: 'act' | 'scene'
  id: string
  owner: string
  original: string
}

export function collectQuotes(): { scenario: Scenario; items: QuoteItem[] }[] {
  return SCENARIOS.map((scenario) => {
    const items: QuoteItem[] = []
    for (const act of scenario.acts) {
      items.push({ kind: 'act', id: act.id, owner: act.title, original: act.quote })
      for (const scene of act.scenes) {
        items.push({ kind: 'scene', id: scene.id, owner: scene.title, original: scene.quote })
      }
    }
    return { scenario, items }
  })
}
