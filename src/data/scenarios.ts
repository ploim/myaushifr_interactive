export const SCENARIOS: readonly Scenario[] = [malicious, edr, net, ips, dlp, brute]

// ----------------------------------------------------------------------------
// Плоский список шагов прогона
// ----------------------------------------------------------------------------
export interface Step {
  scenario: Scenario
  act: Act
  actIndex: number
  actFirstScene: boolean
  scene: Scene
  index: number
  total: number
}

export function flatten(scenario: Scenario): Step[] {
  const known = new Set(scenario.stages.map((s) => s.id))
  const steps: Step[] = []
  for (const [actIndex, act] of scenario.acts.entries()) {
    act.scenes.forEach((scene, sceneIndex) => {
      if (!known.has(scene.stage)) {
        throw new Error(`Сцена ${scene.id}: неизвестный узел трека «${scene.stage}»`)
      }
      steps.push({
        scenario,
        act,
        actIndex,
        actFirstScene: sceneIndex === 0,
        scene,
        index: steps.length,
        total: 0,
      })
    })
  }
  return steps.map((s) => ({ ...s, total: steps.length }))
}
