// Сюжеты демонстрации: акты, сцены, участники-СЗИ и реплики маскота.
// Все тексты — концептуальные, это демонстрация принципов, а не реальный анализ.
import type { PixelMap } from '../pixel/maps'
import { STAGES, type Stage, type StageId } from './stages'

export type Mood = 'idle' | 'happy' | 'analyze' | 'alarm'

/** Результат шага. Определяет цвет бейджа и поведение трека. */
export type SceneStatus = 'info' | 'pass' | 'warn' | 'unknown' | 'block' | 'deliver'

export interface Speaker {
  name: string
  /** Короткая пиксельная плашка: кто говорит. */
  badge: string
  /** Иконка спикера — совпадает с иконкой узла сцены. */
  icon: PixelMap
  /** Стиль «вне защиты» — для атакующего и нейтральных персонажей. */
  tone: 'szi' | 'outside'
  /** Экран иконки красный (атакующий). */
  evil?: boolean
}

export interface Scene {
  id: string
  title: string
  stage: StageId
  status: SceneStatus
  statusLabel: string
  speaker: Speaker
  /** Концептуальная функция средства защиты (для карточки). */
  sziRole?: string
  /** Объяснение от лица спикера. */
  narration: string
  mood: Mood
  /** Исходная реплика маскота (редактируется пользователем). */
  quote: string
  /** Финальная сцена: вместо панели — итоговая карточка. */
  finale?: boolean
  /** Конверт на треке едет «под замком». */
  letterLocked?: boolean
}

export interface Act {
  id: string
  title: string
  /** Реплика маскота на весь акт (показывается на первой сцене акта). */
  quote: string
  scenes: Scene[]
}

export interface Scenario {
  id: 'malicious' | 'legit'
  title: string
  tagline: string
  /** Плашка уровня угрозы на карточке выбора. */
  threat: string
  outcome: 'blocked' | 'delivered'
  /** Подписи узлов, зависящие от сценария. */
  stageLabels: Partial<Record<StageId, string>>
  /** Итоговая карточка. */
  verdictTitle: string
  verdictSubtitle: string
  summary: readonly { status: SceneStatus; text: string }[]
  acts: Act[]
}

const stageBy = (id: StageId): Stage => STAGES.find((s) => s.id === id)!
const speakerIcon = (id: StageId): PixelMap => stageBy(id).icon

